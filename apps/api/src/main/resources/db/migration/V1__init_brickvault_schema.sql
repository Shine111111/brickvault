-- BrickVault schema aligned 100% with JPA entities & Hibernate 6 physical naming

CREATE SEQUENCE IF NOT EXISTS account_seq START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE IF NOT EXISTS lego_set_seq START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE IF NOT EXISTS collection_item_seq START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE IF NOT EXISTS borrow_request_seq START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE IF NOT EXISTS registration_seq START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE IF NOT EXISTS review_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE IF NOT EXISTS account (
    id                          INTEGER PRIMARY KEY,
    name                        VARCHAR(255) NOT NULL,
    email                       VARCHAR(255) NOT NULL UNIQUE,
    password                    VARCHAR(255) NOT NULL,
    reset_password_token        VARCHAR(255) UNIQUE,
    reset_password_token_expiry TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS game_owner (
    id INTEGER PRIMARY KEY REFERENCES account(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS lego_set (
    id                          INTEGER PRIMARY KEY,
    set_number                  VARCHAR(255) NOT NULL UNIQUE,
    name                        VARCHAR(255) NOT NULL,
    theme                       VARCHAR(255) NOT NULL,
    piece_count                 INTEGER      NOT NULL CHECK (piece_count > 0),
    release_year                INTEGER      NOT NULL CHECK (release_year >= 1949),
    retail_price_cad            NUMERIC(10, 2),
    estimated_resale_value_cad  NUMERIC(10, 2),
    retirement_status           VARCHAR(255) NOT NULL DEFAULT 'ACTIVE',
    image_url                   VARCHAR(255),
    description                 VARCHAR(1000)
);

CREATE TABLE IF NOT EXISTS collection_item (
    id                  INTEGER PRIMARY KEY,
    lego_set_id         INTEGER      NOT NULL REFERENCES lego_set(id) ON DELETE CASCADE,
    owner_id            INTEGER      NOT NULL REFERENCES account(id) ON DELETE CASCADE,
    condition           VARCHAR(255) NOT NULL DEFAULT 'BUILT_DISPLAY',
    purchase_price_cad  NUMERIC(10, 2),
    purchase_date       DATE,
    for_trade_or_sale   BOOLEAN      NOT NULL DEFAULT FALSE,
    available           BOOLEAN      NOT NULL DEFAULT TRUE,
    notes               VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS borrow_request (
    id                  INTEGER PRIMARY KEY,
    start_date          TIMESTAMP(6),
    end_date            TIMESTAMP(6),
    status              VARCHAR(255),
    request_date        TIMESTAMP(6),
    requested_set_id    INTEGER REFERENCES lego_set(id) ON DELETE SET NULL,
    collection_item_id  INTEGER REFERENCES collection_item(id) ON DELETE CASCADE,
    requester_id        INTEGER REFERENCES account(id) ON DELETE CASCADE,
    responder_id        INTEGER REFERENCES account(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS lending_record (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_date              TIMESTAMP(6),
    end_date                TIMESTAMP(6),
    status                  VARCHAR(255),
    record_owner_id         INTEGER REFERENCES account(id) ON DELETE CASCADE,
    request_id              INTEGER UNIQUE REFERENCES borrow_request(id) ON DELETE CASCADE,
    is_damaged              BOOLEAN NOT NULL DEFAULT FALSE,
    damage_notes            VARCHAR(1000),
    damage_assessment_date  TIMESTAMP(6),
    damage_severity         INTEGER NOT NULL DEFAULT 0,
    last_modified_date      TIMESTAMP(6),
    last_modified_by        INTEGER,
    status_change_reason    VARCHAR(500),
    closed_by               INTEGER,
    closing_reason          VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS event (
    id                          UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    title                       VARCHAR(255),
    date_time                   TIMESTAMP(6),
    location                    VARCHAR(255),
    description                 VARCHAR(1000),
    current_number_participants INTEGER NOT NULL DEFAULT 0,
    max_participants            INTEGER NOT NULL,
    featured_set_id             INTEGER REFERENCES lego_set(id) ON DELETE SET NULL,
    host_id                     INTEGER REFERENCES account(id) ON DELETE CASCADE,
    collection_item_id          INTEGER REFERENCES collection_item(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS registration (
    id                      INTEGER PRIMARY KEY,
    registration_date       TIMESTAMP(6),
    attendee_id             INTEGER REFERENCES account(id) ON DELETE CASCADE,
    event_registered_for_id UUID    REFERENCES event(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS review (
    id              INTEGER PRIMARY KEY,
    rating          INTEGER NOT NULL,
    comment         VARCHAR(1000),
    date_submitted  TIMESTAMP(6),
    lego_set_id     INTEGER REFERENCES lego_set(id) ON DELETE SET NULL,
    reviewer_id     INTEGER REFERENCES account(id) ON DELETE CASCADE
);
